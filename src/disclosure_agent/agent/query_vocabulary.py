# 계약 사실 조회(Q02)가 요구하는 문서 필드 표기.
#
# 값이 MetricConcept인 이유:
#     event.adapter의 CONTRACT_FIELD_BY_METRIC이 같은 어휘로 문서 필드를 찾는다. 여기서
#     문자열을 따로 쓰면 같은 개념에 두 벌의 이름이 생기고, 한쪽이 바뀔 때 조용히 끊어진다.
#
# 계약기간이 두 필드가 되는 이유:
#     기간은 시작일과 종료일이 함께 있어야 서술된다. 한쪽만 담으면 "2025-09-16부터"까지만
#     답하고 언제 끝나는지를 물었다는 사실이 결과 어디에도 남지 않는다.
#
# 맨 낱말("금액", "기간", "시작일")을 함께 두는 이유:
#     "계약 금액과 기간은?"처럼 앞의 '계약'을 한 번만 쓰는 표현이 실제로 온다. 다만 이
#     낱말들만으로는 판정하지 않는다. query_analyzer._looks_like_contract_fact가 질문에
#     '계약'이 있는지를 먼저 보므로, 매출 질문의 '금액'이 이 경로로 끌려오지 않는다.
#
# 사이 공백을 `\s*`로 읽는 이유:
#     "계약 시작일"·"시작 날짜"처럼 사용자가 띄어 쓰는 자리가 정해져 있지 않다. 표기마다
#     낱말을 적어 두면 빠뜨린 표기가 조용히 막힌다. 질문 전체를 compact하지 않고 이 자리만
#     `\s*`로 여는 이유는 compact의 설명과 같다.
#
# 날짜 표기를 시작일/종료일 계열로 한정하는 이유:
#     문서가 쓰는 이름이 '시작일'·'종료일'이고(event.correction_fields), 답 문장이 쓰는
#     이름도 '계약 시작일'·'계약 종료일'이다(agent.answer_builder). 사용자가 되풀이하는
#     것도 그 두 낱말이다. '개시일'·'만료일' 같은 다른 계열은 이 코퍼스에서 확인된 표기가
#     아니므로 넣지 않는다. 넣는 것은 그 표기가 실제로 오는 것을 본 뒤가 먼저다.
CONTRACT_FIELD_VOCABULARY: tuple[tuple[tuple[MetricConcept, ...], str], ...] = (
    (
        (MetricConcept.CONTRACT_AMOUNT,),
        r"금액",
    ),
    (
        (MetricConcept.CONTRACT_START_DATE, MetricConcept.CONTRACT_END_DATE),
        r"기간",
    ),
    (
        (MetricConcept.CONTRACT_START_DATE,),
        r"시작\s*(?:일자|날짜|일)",
    ),
    (
        (MetricConcept.CONTRACT_END_DATE,),
        r"종료\s*(?:일자|날짜|일)",
    ),
)

# 요구 필드가 돌아오는 차례.
#
# 질문에 적힌 차례를 따르지 않는 이유는, 같은 질문을 다르게 쓴 두 표현이 서로 다른 계획을
# 만들면 그 차이가 답의 차이로 새어 나가기 때문이다. "계약금액과 계약기간"과 "계약 시작일,
# 종료일과 금액"은 같은 세 필드를 요구하며, 같은 계획이 되어야 한다.
CONTRACT_FIELD_ORDER: tuple[MetricConcept, ...] = (
    MetricConcept.CONTRACT_AMOUNT,
    MetricConcept.CONTRACT_START_DATE,
    MetricConcept.CONTRACT_END_DATE,
)

_CONTRACT_FIELD_PATTERNS: tuple[tuple[tuple[MetricConcept, ...], re.Pattern[str]], ...] = tuple(
    (fields, re.compile(pattern)) for fields, pattern in CONTRACT_FIELD_VOCABULARY
)


def find_contract_fields(question: str) -> tuple[MetricConcept, ...]:
    """질문이 요구한 계약 문서 필드를 읽는다. 없으면 빈 튜플이며 추측하지 않는다.

    표현이 겹쳐도 필드는 한 번만 담긴다("계약기간 중 시작일"은 시작일·종료일 둘이다).
    차례는 CONTRACT_FIELD_ORDER가 고정한다.
    """
    found: set[MetricConcept] = set()

    for fields, pattern in _CONTRACT_FIELD_PATTERNS:
        if pattern.search(question):
            found.update(fields)

    return tuple(field for field in CONTRACT_FIELD_ORDER if field in found)


