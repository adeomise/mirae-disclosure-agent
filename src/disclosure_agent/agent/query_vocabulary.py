# 값 여럿을 견주어 달라는 요청의 정본 이름.
#
# agent.calculator와 agent.answer_builder도 같은 값을 쓴다. 집계와 같은 이유로 여기에 둔다.
#
# 여기로 옮긴 이유:
#     예전에는 query_analyzer가 이 이름과 표현 목록을 함께 갖고 있었고, 그 자리의 주석은
#     "비교 표현에는 아직 정규화할 다른 표기가 없다"를 근거로 옮기지 않았다. 그 전제가
#     깨졌다. '견주다'는 대표 질문 밖에서 실제로 오는 표기이며("합쳐서 견주면"), 크기 비교
#     어미도 '더 커' 하나가 아니다("더 크지", "더 클까"). 표기가 여럿이 된 개념은 집계와
#     같은 자리에서 같은 방식으로 옮긴다.
OPERATION_COMPARE = "compare"

# 비교를 요청하는 표현.
#
# 원문에서 읽는다. AGGREGATE_REQUEST_PATTERN과 같은 이유이며, 여러 낱말로 오는 표현만 그
# 자리를 `\s*`로 연다.
#
# 세 갈래로 나눠 둔다. 각 갈래가 서로 다른 말하기 방식이며, 한 패턴으로 합치면 어느 쪽을
# 넓혔는지가 코드에 남지 않는다.
#
#   1. 비교 자체를 이름으로 부른다   "비교해줘", "비교하면"
#   2. 견주다 계열                  "견주면", "견줘", "견준다", "견주어"
#   3. 크기로 묻는다                "더 커", "더 큰", "더 크지", "더 클까", "더 높은"
#
# 어간만 담는 이유는 집계 쪽과 같다. 어미는 사용자가 자유롭게 바꾸며("견주면"·"견주고"·
# "견주어"), 어미까지 적으면 목록에 없는 활용이 조용히 막힌다.
#
#   견주        견주다·견주면·견주어·견주고
#   견줘·견준   '견주'의 축약·관형형. 어간 검사로는 걸리지 않아 따로 적는다
#
# '대비'를 넣지 않는 이유:
#     "전년 대비"가 기간 표현이다. 비교 표현으로 읽으면 시계열 질문이 기업 간 비교 신호를
#     갖게 된다. 두 뜻으로 쓰이는 표기는 넓히지 않는다.
#
# '어느·어디'를 넣지 않는 이유:
#     의문사는 비교가 아닌 자리에도 온다("어디에 공장이 있어"). 크기 어간이 붙은 자리는
#     아래 3번이 이미 읽으므로, 의문사 자체를 읽을 필요가 없다.
#
# 크기 비교에 '더'를 요구하는 이유:
#     '크다'·'높다'는 비교가 아닌 서술에도 쓰인다("투자 규모가 커"). '더'가 붙어야
#     두 값을 견주는 말이 된다. 사이 공백은 `\s*`로 열어 "더 커"와 "더커"를 같게 읽는다.
#
#     어간을 크/커/큰/클/큽/높으로 한정한다. 앞의 다섯은 '크다' 하나의 활용형이며, 어간
#     하나로는 다 받지 못한다(더 커·더 큰·더 크지·더 클까·더 큽니까).
#
#     '많'을 넣지 않는 이유:
#         '더 많이'는 크기를 견주는 말이 아니라 용언을 꾸미는 말이다("작년보다 더 많이
#         늘었어"). 그 질문이 묻는 것은 시간축의 증가이고 기업 간 우열이 아닌데, '많'을
#         읽으면 집계 표현이 함께 있는 순간 기업 간 집계 비교가 된다. 실제로 "시설투자를
#         합쳐서 작년보다 더 많이 늘었어?"가 그렇게 읽혔다.
#
#         '더 많은'은 크기 비교가 맞지만, 그것 하나를 받자고 '많'을 열면 위 오탐이 함께
#         온다. 이 판정을 쓰는 자리(집계 비교)의 대상 질문 가운데 '많'을 요구하는 것이
#         없으므로 열지 않는다. 여는 것은 그 표기가 실제로 오는 것을 본 뒤가 먼저다.
#
#     '크'에 '게'를 막는 이유:
#         같은 부사형이 '크다'에도 있다("더 크게 늘었어"). 어간을 통째로 빼면 "더 크지"가
#         함께 막히는데, 그것은 이 판정이 실제로 받아야 하는 표기다(BB16의 "어디가 더
#         크지?"). 그래서 어간은 두고 부사형 어미 하나만 막는다.
#
#     '적다'·'작다'는 넣지 않는다. 이 판정을 쓰는 자리(집계 비교)의 실제 표현에서 확인된
#     적이 없고, 넣는 것은 그 표기가 오는 것을 본 뒤가 먼저다.
COMPARISON_REQUEST_PATTERN = re.compile(
    r"비교"
    r"|견주|견줘|견준"
    r"|더\s*(?:크(?!게)|커|큰|클|큽|높)"
)


def normalize_comparison_request(question: str) -> str | None:
    """질문이 비교를 요청했으면 정본 이름으로 옮긴다. 아니면 None이며 추측하지 않는다."""
    if COMPARISON_REQUEST_PATTERN.search(question) is None:
        return None

    return OPERATION_COMPARE
