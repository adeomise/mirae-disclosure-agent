"""질의 표현 정규화 어휘 모듈.

역할:
- 사용자가 같은 것을 다르게 쓴 표현을 정본(canonical) 값 하나로 옮긴다.
- 옮기는 규칙과 그 규칙이 읽는 어휘를 한자리에 둔다.

query_analyzer에서 떼어 낸 이유:
    같은 개념을 가리키는 표현이 늘 때마다 판정 자리마다 부분문자열 검사가 하나씩 붙었다.
    검사가 흩어지면 어휘를 넓힐 때 어느 자리를 함께 넓혀야 하는지가 코드에 남지 않고,
    한 자리만 넓힌 날 같은 질문이 경로에 따라 다르게 읽힌다. 그 차이는 결과의 형식으로는
    드러나지 않으므로, 어휘와 정규화를 이 모듈 하나로 모은다.

여기 담는 것과 담지 않는 것:
    담는 것은 "질문에 적힌 말을 이 구현의 어휘로 옮기는 규칙"뿐이다. 옮긴 값으로 무엇을
    할지(어느 의도로 가를지, 무엇을 요구하고 무엇을 막을지)는 query_analyzer가 정한다.
    그 분업이 있어야 어휘를 넓히는 변경이 판정 순서를 건드리지 않는다.

넓히는 방향에 대해:
    넓게 잡으면 답할 수 있는 질문이 늘지만, 틀리게 읽은 질문은 형식이 맞는 답을 내므로
    틀렸다는 사실이 드러나지 않는다. 그래서 표현을 넓힐 때마다 "이 표기가 다른 뜻으로도
    쓰이는가"를 먼저 본다. 쓰인다면 넓히지 않고, 넓힌 자리에는 그 판단을 주석으로 남긴다.
"""

