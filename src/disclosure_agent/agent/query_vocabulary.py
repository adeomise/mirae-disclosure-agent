# 여러 값을 하나로 더해 달라는 요청의 정본 이름.
#
# agent.calculator와 agent.answer_builder도 같은 값을 쓴다. 계산 결과에 적히는 이름이므로
# 여기서 옮긴 값과 그쪽이 읽는 값이 어긋나면 안 된다.
OPERATION_AGGREGATE = "aggregate"

# 집계를 요청하는 표현.
#
# 원문에서 읽는다. compact하지 않는 이유:
#     공백을 걷어내면 떨어져 있던 두 낱말이 붙어 이 어휘를 만든다. "통합 계획"이
#     "통합계획"이 되면 '합계'가 생기고, 집계를 요청하지 않은 질문이 집계로 읽힌다.
#     그래서 원문을 보고, 여러 낱말로 오는 표현만 그 자리를 `\s*`로 연다.
#
# 어간만 담는 이유:
#     어미는 사용자가 자유롭게 바꾼다("합치면"·"합치고"·"합쳐서"·"합산해줘"). 어미까지
#     적으면 목록에 없는 활용이 조용히 막힌다. 어간은 그 활용을 전부 받는다.
#
#   합치        합치다·합치면·합치고
#   합쳐·합친   '합치'의 축약형. 어간 검사로는 걸리지 않아 따로 적는다
#   합산        합산·합산해·합산하면
#   합계·총합   명사형
#
# '합해'를 넣지 않은 이유:
#     "종합해서 알려줘"가 그 표기를 담고 있고, 그것은 집계 요청이 아니라 요약 요청으로도
#     쓰인다. 두 뜻으로 쓰이는 표기는 넓히지 않는다.
#
# '더하다' 계열에 수량 표현을 요구하는 이유:
#     '더'는 비교 표현("작년보다 더 늘었어")에 훨씬 자주 쓰인다. 낱말 하나로 보면 비교
#     질문이 집계로 읽힌다. 그래서 앞에 전부·모두·전체가 붙고 '더'와 '하-'가 붙어 있는
#     자리만 읽는다. "전부 더 하락했어"는 '더'와 '하락' 사이가 떨어져 있어 걸리지 않는다.
#
#     '다 더해'는 넣지 않는다. "~보다 더해"가 같은 글자를 담고 있어 비교 질문을 끌어온다.
# 이력이 몇 차례 정정됐는지를 세는 요청. QueryPlan.operations의 어휘다.
OPERATION_CHANGE_COUNT = "change_count"


AGGREGATE_REQUEST_PATTERN = re.compile(
    r"합치|합쳐|합친"
    r"|합산"
    r"|합계|총합"
    r"|(?:전부|모두|전체)\s*더(?:해|한|하면|하고|하기|할|합)"
)


# 정정이 몇 차례 있었는지를 묻는 표현.
#
# 이력 질문에는 두 갈래가 있다. "무엇이 바뀌었어?"는 바뀐 내용을 묻고, "몇 번 바뀌었어?"는
# 바뀐 횟수를 묻는다. 앞쪽은 변경 항목으로 답하고 뒤쪽은 정정 이력의 개수로 답하는데, 두 값이
# 다르다. Q15 실측이 변경 항목 4건에 정정 3회다. 계획이 이 구분을 담지 않으면 어느 쪽을 묻든
# 같은 문장이 나가고, 횟수를 물은 질문은 답을 받지 못한다.
#
# 수량 표현을 요구한다:
#     '번'과 '회'는 횟수가 아닌 자리에 훨씬 자주 쓰인다("이번", "1회차", "번호"). 그래서
#     '몇'이 앞에 붙은 자리만 읽는다. "몇 번째"는 넣지 않는다. 순서를 묻는 말이고 답이
#     개수가 아니다.
#
# 이 판정은 여기까지다. 무엇을 세는지는 계획이 정하고(query_analyzer의 이력 계획),
# 그 값을 어떻게 적을지는 문장을 만드는 쪽이 정한다(answer_builder).
CHANGE_COUNT_REQUEST_PATTERN = re.compile(r"몇\s*(?:번|회|차례)(?!째)")


def normalize_change_count_request(question: str) -> str | None:
    """질문이 정정 횟수를 요청했으면 정본 이름으로 옮긴다. 아니면 None이며 추측하지 않는다."""
    if CHANGE_COUNT_REQUEST_PATTERN.search(question) is None:
        return None

    return OPERATION_CHANGE_COUNT


def normalize_aggregate_request(question: str) -> str | None:
    """질문이 집계를 요청했으면 정본 이름으로 옮긴다. 아니면 None이며 추측하지 않는다."""
    if AGGREGATE_REQUEST_PATTERN.search(question) is None:
        return None

    return OPERATION_AGGREGATE


# 여러 건을 뭉뚱그려 '규모'라고 부르는 표현.
#
# 왜 AGGREGATE_REQUEST_PATTERN과 나눠 두는가:
#     위 어휘는 사용자가 더해 달라고 말한 표현이다("다 합치면"). '규모'는 그렇지 않다.
#     값 하나의 크기를 부르는 자리에 훨씬 자주 쓰이며("2025년 매출 규모 알려줘", "계약
#     규모가 얼마야"), 그 질문은 집계를 요청하지 않았다. 위 어휘에 넣으면 값 하나를 물은
#     질문이 전부 집계 요청이 되고, 형식이 맞는 답이 나가므로 틀렸다는 사실이 드러나지
#     않는다. 그래서 같은 모듈에 두되 다른 이름으로 두고, 읽을지 말지는 부르는 쪽이 정한다.
#
# 어디서 읽어도 되는가:
#     묻는 대상이 이미 '여러 건'으로 확정된 자리에서만이다. 그 자리에서는 '규모'가 가리킬
#     수 있는 것이 그 여러 건의 합계 말고 없다. 지금 그 조건을 갖춘 부르는 쪽은
#     query_analyzer._looks_like_facility_investment_aggregate 하나뿐이다. 그쪽은 질문이
#     신규시설투자등 공시를 가리켰다는 것을 이미 확정한 뒤에 이것을 읽으며, 한 해에 그
#     공시는 기업마다 여러 건이다.
#
#     문서 하나의 값을 묻는 자리(Pattern A·B)에서는 읽지 않는다. 읽으면 위에 적은 오탐이
#     그대로 일어난다.
#
# 표기:
#     '규모' 하나다. '총액'·'전체'처럼 뜻이 가까운 표기를 함께 넣지 않는다. 넣는 것은 그
#     표기가 실제로 오는 것을 본 뒤가 먼저이며, 이 모듈이 넓힐 때마다 지키는 순서다.
SCALE_REQUEST_PATTERN = re.compile(r"규모")


def normalize_scale_request(question: str) -> str | None:
    """질문이 '규모'로 여러 건을 뭉뚱그렸으면 집계의 정본 이름으로 옮긴다.

    부르기 전에 SCALE_REQUEST_PATTERN의 설명을 읽는다. 묻는 대상이 여러 건으로 확정된
    자리에서만 부를 수 있으며, 그렇지 않은 자리에서 부르면 값 하나를 물은 질문이 집계
    요청으로 읽힌다.
    """
    if SCALE_REQUEST_PATTERN.search(question) is None:
        return None

    return OPERATION_AGGREGATE


