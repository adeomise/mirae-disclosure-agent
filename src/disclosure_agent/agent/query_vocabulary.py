def compact(question: str) -> str:
    """질문에서 공백을 모두 걷어낸다.

    띄어쓰기는 같은 말을 여러 표기로 만든다("주력 제품"·"주력제품", "계약 기간"·"계약기간").
    표기마다 어휘를 적어 두면 한쪽을 빠뜨렸을 때 답할 수 있던 질문이 조용히 막힌다.

    다만 공백을 걷어내면 원래 떨어져 있던 두 낱말이 붙어 새 낱말을 만든다("통합 계획" ->
    "통합계획"에 '합계'가 생긴다). 그래서 이 정규화를 모든 판정에 쓰지 않는다. 낱말이 붙어
    다른 뜻이 생길 수 있는 어휘는 원문에서 `\\s*`로 읽는다(AGGREGATE_REQUEST_PATTERN).
    """
    return "".join(question.split())


